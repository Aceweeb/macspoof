"""Locating (and optionally installing) the privileged helper.

`pkexec` starts the program with a sanitised environment in root's home
directory, so the helper cannot rely on the user's `PYTHONPATH` or virtualenv.
Two strategies are used:

1. A system-wide helper installed at ``/usr/local/libexec/macspoof-helper``,
   owned by root and accompanied by a polkit action.  This is the preferred
   setup because it lets the polkit agent remember the authorisation.
2. A wrapper script rendered into a private temporary directory with the
   correct import path baked in.  It works without any system-wide setup but
   requires a fresh authentication for every action.
"""

from __future__ import annotations

import os
import stat
import sys
import tempfile

SYSTEM_HELPER_PATH = "/usr/local/libexec/macspoof-helper"
SYSTEM_POLICY_PATH = "/usr/share/polkit-1/actions/org.macspoof.policy"
HELPER_ARGV1 = ("set", "restore", "persist")

# Temporary wrapper directories created during this session.
_FALLBACK_DIRS: list[str] = []


def _package_root() -> str:
    """Directory that must be on sys.path to import the `macspoof` package.

    This is the parent of the package directory, so that `import macspoof`
    works.  It resolves correctly both from a source checkout and from an
    installed copy in site-packages.
    """
    here = os.path.abspath(__file__)          # .../macspoof/gui/helperpath.py
    return os.path.dirname(os.path.dirname(os.path.dirname(here)))


def render_helper_script() -> str:
    """Render a self-contained wrapper that runs the privileged helper.

    The interpreter and the import path are baked in so the script keeps
    working under pkexec's sanitised environment.
    """
    package_root = _package_root()
    return f"""#!/bin/sh
# Generated by macspoof. Runs the macspoof privileged helper.
PYTHONPATH="{package_root}"${{PYTHONPATH:+:$PYTHONPATH}}
export PYTHONPATH
exec "{sys.executable}" -m macspoof.helper "$@"
"""


def system_helper_exists() -> bool:
    return os.path.isfile(SYSTEM_HELPER_PATH) and os.access(SYSTEM_HELPER_PATH, os.X_OK)


def _private_dir() -> str:
    """A directory only the current user can read, for the fallback wrapper."""
    path = tempfile.mkdtemp(prefix="macspoof-")
    os.chmod(path, stat.S_IRWXU)
    _FALLBACK_DIRS.append(path)
    return path


def fallback_helper() -> str:
    """Create a temporary wrapper script and return its path."""
    directory = _private_dir()
    script_path = os.path.join(directory, "macspoof-helper")
    with open(script_path, "w") as handle:
        handle.write(render_helper_script())
    os.chmod(script_path, stat.S_IRWXU)
    return script_path


def helper_command() -> list[str]:
    """The privileged program to hand to pkexec."""
    if system_helper_exists():
        return [SYSTEM_HELPER_PATH]
    return [fallback_helper()]


def cleanup_fallback() -> None:
    """Remove any temporary wrapper created by `helper_command`."""
    while _FALLBACK_DIRS:
        directory = _FALLBACK_DIRS.pop()
        script = os.path.join(directory, "macspoof-helper")
        try:
            if os.path.isfile(script):
                os.remove(script)
            os.rmdir(directory)
        except OSError:
            pass


POLICY_TEMPLATE = """<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE policyconfig PUBLIC
 "-//freedesktop//DTD PolicyKit Policy Configuration 1.0//EN"
 "http://www.freedesktop.org/standards/PolicyKit/1/policyconfig.dtd">
<policyconfig>
  <vendor>macspoof</vendor>
  <vendor_url>https://github.com/local/macspoof</vendor_url>
  <icon_name>network-wired-symbolic</icon_name>
  <action id="org.macspoof.helper">
    <description>Change the MAC address of a network interface</description>
    <message>Authentication is required to change the MAC address of a network interface.</message>
    <defaults>
      <allow_any>auth_admin</allow_any>
      <allow_inactive>auth_admin</allow_inactive>
      <allow_active>auth_admin_keep</allow_active>
    </defaults>
{argv_annotations}  </action>
</policyconfig>
"""


def render_policy() -> str:
    annotations = "".join(
        f'    <annotate key="org.freedesktop.policykit.exec.argv1">{name}</annotate>\n'
        for name in HELPER_ARGV1
    )
    return POLICY_TEMPLATE.format(argv_annotations=annotations)


def install_system_helper() -> tuple[bool, str]:
    """Install the root-owned helper and polkit policy.

    Must run as root.  Returns (success, message).
    """
    if not hasattr(os, "geteuid") or os.geteuid() != 0:
        return False, "must run as root"

    try:
        os.makedirs(os.path.dirname(SYSTEM_HELPER_PATH), exist_ok=True)
        with open(SYSTEM_HELPER_PATH, "w") as handle:
            handle.write(render_helper_script())
        os.chmod(SYSTEM_HELPER_PATH, 0o755)

        os.makedirs(os.path.dirname(SYSTEM_POLICY_PATH), exist_ok=True)
        with open(SYSTEM_POLICY_PATH, "w") as handle:
            handle.write(render_policy())
        os.chmod(SYSTEM_POLICY_PATH, 0o644)
    except OSError as exc:
        return False, f"install failed: {exc}"

    return True, f"installed helper at {SYSTEM_HELPER_PATH} and polkit policy at {SYSTEM_POLICY_PATH}"
